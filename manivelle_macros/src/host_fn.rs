//! Expansion of `#[host_fn]`.

use proc_macro2::TokenStream;
use quote::{format_ident, quote};
use syn::{
    Error, FnArg, GenericArgument, Ident, ItemFn, LitStr, PathArguments, ReturnType, Type,
    spanned::Spanned,
};

use crate::args::{parse_args, take_flag, take_value};

/// What the parameters say the host function is: `[ctx: &Caller<'_>,] [input,]
/// [resolver: HostResolver<Output>]`.
struct Shape<'a> {
    /// Whether it receives the calling script.
    ctx: bool,
    /// The type of its one input, when it takes one.
    input: Option<&'a Type>,
    /// The type of its resolver, when it settles a `Promise` later.
    resolver: Option<&'a Type>,
}

/// The parts of the signature the contract is made of.
struct Signature {
    input: Type,
    output: Type,
    /// The call of the function from its arguments (`ctx`, `input`, `resolver`).
    call: TokenStream,
    /// The registry method that takes the function's handler; `None` for a function
    /// that needs neither the caller nor a resolver, which is a static `HostFunction`.
    register_with: Option<Ident>,
    /// The parameters of the closure that calls the function when registering it.
    params: TokenStream,
}

/// Expands the attribute: keeps the function and adds the marker type implementing
/// `HostContract` and `HostFunctionSignature` for it, plus `HostFunction` for a static
/// function or `RegisterHostFunction` for the others (a static function gets it from
/// the blanket impl over `HostFunction`).
pub(crate) fn expand_host_fn(args: TokenStream, function: &ItemFn) -> syn::Result<TokenStream> {
    let span = args.span();
    let parsed = HostFnArgs::parse(args)?;
    if let Some(reply) = &parsed.reply {
        return Err(Error::new(
            reply.span(),
            "`reply` belongs to `#[host_event]`, not to a host function",
        ));
    }
    let name = parsed
        .name
        .ok_or_else(|| Error::new(span, "missing `name = \"contract.name\"`"))?;
    check_shape(function)?;

    let marker = marker_ident(&function.sig.ident);
    let vis = &function.vis;
    let signature = signature(function)?;
    let (input, output) = (&signature.input, &signature.output);
    let doc = format!(
        "Host function contract `{}`, generated by `#[host_fn]`.",
        name.value()
    );
    let docs = doc_text(&function.attrs);
    let docs_const = (!docs.is_empty()).then(|| quote!(const DOCS: &'static str = #docs;));
    let import_consts = import_consts(parsed.import.as_ref(), &name);
    let implementation = match &signature.register_with {
        None => static_impl(&marker, &signature),
        Some(method) => register_impl(&marker, &signature, method),
    };

    Ok(quote! {
        #function

        #[doc = #doc]
        #vis struct #marker;

        impl ::manivelle::HostContract for #marker {
            const NAME: &'static str = #name;
            #docs_const
            #import_consts

            fn kind() -> ::manivelle::HostContractKind {
                ::manivelle::HostContractKind::Function
            }
        }

        impl ::manivelle::HostFunctionSignature for #marker {
            type Input = #input;
            type Output = #output;
        }

        #implementation
    })
}

/// The `///` comments of the function as Markdown: one line per comment line, without the
/// space every `///` leaves in front of its text.
pub(crate) fn doc_text(attrs: &[syn::Attribute]) -> String {
    let lines: Vec<String> = attrs
        .iter()
        .filter(|attr| attr.path().is_ident("doc"))
        .filter_map(|attr| match &attr.meta {
            syn::Meta::NameValue(pair) => match &pair.value {
                syn::Expr::Lit(syn::ExprLit {
                    lit: syn::Lit::Str(text),
                    ..
                }) => Some(text.value()),
                _ => None,
            },
            _ => None,
        })
        .flat_map(|text| {
            text.split('\n')
                .map(|line| line.strip_prefix(' ').unwrap_or(line).to_owned())
                .collect::<Vec<_>>()
        })
        .collect();
    lines.join("\n").trim().to_owned()
}

fn static_impl(marker: &Ident, signature: &Signature) -> TokenStream {
    let call = &signature.call;
    quote! {
        impl ::manivelle::HostFunction for #marker {
            fn call(
                input: <Self as ::manivelle::HostFunctionSignature>::Input,
            ) -> ::core::result::Result<
                <Self as ::manivelle::HostFunctionSignature>::Output,
                ::manivelle::EngineError,
            > {
                #call
            }
        }
    }
}

/// `impl RegisterHostFunction for Marker`, which registers the function with its handler.
fn register_impl(marker: &Ident, signature: &Signature, method: &Ident) -> TokenStream {
    let call = &signature.call;
    let params = &signature.params;
    quote! {
        impl ::manivelle::RegisterHostFunction for #marker {
            fn register_in(
                registry: &::manivelle::InMemoryHostContractRegistry,
            ) -> ::core::result::Result<
                &::manivelle::InMemoryHostContractRegistry,
                ::manivelle::EngineError,
            > {
                registry.#method::<Self>(#params #call)
            }
        }
    }
}

/// Reads the input and output types, and the call of the function.
fn signature(function: &ItemFn) -> syn::Result<Signature> {
    let shape = shape(function)?;
    let fn_ident = &function.sig.ident;
    let (returned, fallible) = output_type(function)?;
    let ctx = shape.ctx.then(|| quote!(ctx));
    let input = shape.input.map(|_| quote!(input));
    let resolver = shape.resolver.map(|_| quote!(resolver));
    let args = ctx.iter().chain(&input).chain(&resolver);
    // The call of the function, wrapped in `Ok` unless it returns a `Result` itself.
    let call = if fallible {
        quote!(#fn_ident(#(#args),*))
    } else {
        quote!(::core::result::Result::Ok(#fn_ident(#(#args),*)))
    };
    let register_with = match (shape.ctx, shape.resolver.is_some()) {
        (false, false) => None,
        (true, false) => Some("function_with_caller"),
        (false, true) => Some("async_function_with"),
        (true, true) => Some("async_function_with_caller"),
    };
    // The registry hands the handler an input whether the function takes one or not.
    let input_param = input.unwrap_or_else(|| quote!(_input));
    let params = ctx.iter().chain([&input_param]).chain(&resolver);
    Ok(Signature {
        input: shape
            .input
            .map_or_else(|| syn::parse_quote!(()), Clone::clone),
        // An async function answers through its resolver, not through what it returns.
        output: shape.resolver.map_or(Ok(returned), resolver_output)?,
        call,
        register_with: register_with.map(|method| format_ident!("{method}")),
        params: quote!(|#(#params),*|),
    })
}

/// Tells the caller and the resolver from the input by their types: a leading
/// `&Caller<'_>` and a trailing `HostResolver<Output>`, under any path.
fn shape(function: &ItemFn) -> syn::Result<Shape<'_>> {
    let types: Vec<&Type> = function
        .sig
        .inputs
        .iter()
        .filter_map(|arg| match arg {
            FnArg::Typed(arg) => Some(arg.ty.as_ref()),
            FnArg::Receiver(_) => None,
        })
        .collect();
    let mut inputs = types.as_slice();
    let ctx = inputs.first().is_some_and(|ty| is_caller(ty));
    if ctx {
        inputs = &inputs[1..];
    }
    let resolver = inputs
        .last()
        .copied()
        .filter(|ty| is_named(ty, "HostResolver"));
    if resolver.is_some() {
        inputs = &inputs[..inputs.len() - 1];
    }
    match inputs {
        [] => Ok(Shape {
            ctx,
            input: None,
            resolver,
        }),
        [input] => Ok(Shape {
            ctx,
            input: Some(input),
            resolver,
        }),
        _ => Err(Error::new(
            function.sig.inputs.span(),
            "a host function takes at most one input (group fields in a struct), after an \
             optional `ctx: &Caller<'_>` and before an optional `resolver: HostResolver<Output>`",
        )),
    }
}

/// Whether `ty` is a reference to a path ending in `Caller`.
fn is_caller(ty: &Type) -> bool {
    matches!(ty, Type::Reference(reference) if is_named(&reference.elem, "Caller"))
}

/// Whether `ty` is a path ending in `name`.
fn is_named(ty: &Type, name: &str) -> bool {
    matches!(ty, Type::Path(path) if path.path.segments.last().is_some_and(|s| s.ident == name))
}

/// The `T` of the `HostResolver<T>` an async host function receives.
fn resolver_output(ty: &Type) -> syn::Result<Type> {
    let expected = "the last parameter must be a `HostResolver<Output>`";
    let Type::Path(path) = ty else {
        return Err(Error::new(ty.span(), expected));
    };
    let last = path
        .path
        .segments
        .last()
        .filter(|s| s.ident == "HostResolver");
    let Some(PathArguments::AngleBracketed(generics)) = last.map(|s| &s.arguments) else {
        return Err(Error::new(ty.span(), expected));
    };
    match generics.args.first() {
        Some(GenericArgument::Type(output)) => Ok(output.clone()),
        _ => Err(Error::new(ty.span(), expected)),
    }
}

/// The argument under which `#[host_mod(import = "...")]` hands its import module to the
/// attributes it rewrites. Reserved: only the module writes it.
pub(crate) const MOD_IMPORT_KEY: &str = "__host_mod_import";

/// Arguments of the host function attributes: `name = "..."` and the `no_namespace` flag.
#[derive(Default)]
pub(crate) struct HostFnArgs {
    /// The contract name; the full name outside a `#[host_mod]`.
    pub(crate) name: Option<LitStr>,
    /// Opts out of the enclosing `#[host_mod]` prefix; `name` is then the full name.
    pub(crate) no_namespace: bool,
    /// The `reply` type of a `#[host_event]` that is a request.
    pub(crate) reply: Option<Type>,
    /// The import module `#[host_mod(import = "...")]` gives its contracts, read from
    /// [`MOD_IMPORT_KEY`].
    pub(crate) import: Option<LitStr>,
}

impl HostFnArgs {
    pub(crate) fn parse(args: TokenStream) -> syn::Result<Self> {
        let mut parsed = Self::default();
        parse_args(
            args,
            "expected `name = \"contract.name\"`, and optionally `no_namespace` \
             or, for an event, `reply = Type`",
            |meta| {
                if meta.path.is_ident("import") {
                    return Err(meta.error(
                        "`import` belongs to the module: write `#[host_mod(import = \"module\")]`",
                    ));
                }
                Ok(take_value(meta, "name", &mut parsed.name)?
                    || take_flag(meta, "no_namespace", &mut parsed.no_namespace)
                    || take_value(meta, "reply", &mut parsed.reply)?
                    || take_value(meta, MOD_IMPORT_KEY, &mut parsed.import)?)
            },
        )?;
        Ok(parsed)
    }
}

/// An import module with no name would leave the contract unimportable without saying so.
pub(crate) fn check_import(import: &LitStr) -> syn::Result<()> {
    if import.value().is_empty() {
        return Err(Error::new(
            import.span(),
            "`import` needs the name of the module scripts import from",
        ));
    }
    Ok(())
}

/// `IMPORT_MODULE` and `EXPORT_PATH` of a contract imported from `import`: scripts reach
/// it at the path of its name, as they do under the global namespace (`math.add` is
/// `import { math } from "app"; math.add(...)`).
pub(crate) fn import_consts(import: Option<&LitStr>, name: &LitStr) -> Option<TokenStream> {
    let module = import?;
    let path = name.value();
    let segments = path.split('.');
    Some(quote! {
        const IMPORT_MODULE: &'static str = #module;
        const EXPORT_PATH: &'static [&'static str] = &[#(#segments),*];
    })
}

fn check_shape(function: &ItemFn) -> syn::Result<()> {
    let sig = &function.sig;
    if sig.asyncness.is_some() {
        return Err(Error::new(
            sig.asyncness.span(),
            "a host function cannot be `async fn`; take a `resolver: HostResolver<Output>` as the last parameter to answer later",
        ));
    }
    if !sig.generics.params.is_empty() {
        return Err(Error::new(
            sig.generics.span(),
            "a host function cannot be generic",
        ));
    }
    if let Some(FnArg::Receiver(receiver)) = sig.inputs.first() {
        return Err(Error::new(
            receiver.span(),
            "a host function cannot take `self`",
        ));
    }
    Ok(())
}

/// The `Output` type, and whether the function returns `Result<Output, EngineError>`;
/// any other return type, or none, is an infallible `Output` the call wraps in `Ok`.
fn output_type(function: &ItemFn) -> syn::Result<(Type, bool)> {
    let ReturnType::Type(_, ty) = &function.sig.output else {
        return Ok((syn::parse_quote!(()), false));
    };
    let Type::Path(path) = ty.as_ref() else {
        return Ok((ty.as_ref().clone(), false));
    };
    let Some(last) = path.path.segments.last().filter(|s| s.ident == "Result") else {
        return Ok((ty.as_ref().clone(), false));
    };
    let PathArguments::AngleBracketed(generics) = &last.arguments else {
        return Err(Error::new(
            ty.span(),
            "expected `Result<Output, EngineError>`",
        ));
    };
    let Some(GenericArgument::Type(output)) = generics.args.first() else {
        return Err(Error::new(
            ty.span(),
            "expected `Result<Output, EngineError>`",
        ));
    };
    if let Some(GenericArgument::Type(error)) = generics.args.iter().nth(1)
        && !is_engine_error(error)
    {
        return Err(Error::new(
            error.span(),
            "a host function must return `Result<Output, EngineError>`",
        ));
    }
    Ok((output.clone(), true))
}

/// Whether `ty` is a path ending in `EngineError`.
fn is_engine_error(ty: &Type) -> bool {
    matches!(ty, Type::Path(path) if path.path.segments.last().is_some_and(|s| s.ident == "EngineError"))
}

/// `find_user` → `FindUser`.
fn marker_ident(function: &Ident) -> Ident {
    let name: String = function
        .to_string()
        .trim_start_matches("r#")
        .split('_')
        .filter(|part| !part.is_empty())
        .map(|part| {
            let mut chars = part.chars();
            chars
                .next()
                .map(|first| first.to_uppercase().chain(chars).collect::<String>())
                .unwrap_or_default()
        })
        .collect();
    format_ident!("{}", name, span = function.span())
}
