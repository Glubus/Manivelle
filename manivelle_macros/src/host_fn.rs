//! Expansion of `#[host_fn]`, `#[host_fn_with_ctx]` and `#[host_fn_async]`.

use proc_macro2::TokenStream;
use quote::{format_ident, quote};
use std::ops::RangeInclusive;
use syn::{
    Error, FnArg, GenericArgument, Ident, ItemFn, LitStr, PathArguments, ReturnType, Type,
    spanned::Spanned,
};

use crate::args::{parse_args, take_flag, take_value};

/// The three shapes of host function the attributes declare.
#[derive(Clone, Copy, PartialEq, Eq)]
pub(crate) enum Kind {
    /// `fn(input)`: a static `HostFunction`.
    Static,
    /// `fn(ctx, input)`: registered with `function_with_caller`.
    WithCtx,
    /// `fn([ctx,] input, resolver)`: registered as an async function.
    Async,
}

impl Kind {
    fn attribute(self) -> &'static str {
        match self {
            Self::Static => "host_fn",
            Self::WithCtx => "host_fn_with_ctx",
            Self::Async => "host_fn_async",
        }
    }

    /// The number of inputs the function takes, and how the error names them.
    fn arity(self) -> (RangeInclusive<usize>, &'static str) {
        match self {
            Self::Static => (
                0..=1,
                "at most one input (group fields in a struct); use `#[host_fn_with_ctx]` to receive the `Caller`",
            ),
            Self::WithCtx => (1..=2, "`ctx: &Caller<'_>` and at most one input"),
            Self::Async => (
                2..=3,
                "`[ctx: &Caller<'_>,] input, resolver: HostResolver<Output>`",
            ),
        }
    }
}

/// The parts of the signature the contract is made of.
struct Signature {
    input: Type,
    output: Type,
    /// The call of the function from its arguments (`ctx`, `input`, `resolver`).
    call: TokenStream,
    /// Whether the handler takes the `Caller`.
    with_ctx: bool,
    /// The parameters of the closure that calls the function when registering it.
    params: TokenStream,
}

/// Expands the attribute: keeps the function and adds the marker type implementing
/// `HostContract` and `HostFunctionSignature` for it, plus `HostFunction` for a static
/// function or a `register` function for the others.
pub(crate) fn expand_host_fn(
    args: TokenStream,
    function: &ItemFn,
    kind: Kind,
) -> syn::Result<TokenStream> {
    let span = args.span();
    let parsed = HostFnArgs::parse(args)?;
    if let Some(reply) = &parsed.reply {
        return Err(Error::new(
            reply.span(),
            "`reply` belongs to `#[host_event]`, not to a host function",
        ));
    }
    let name = parsed
        .name
        .ok_or_else(|| Error::new(span, "missing `name = \"contract.name\"`"))?;
    check_shape(function, kind)?;

    let marker = marker_ident(&function.sig.ident);
    let vis = &function.vis;
    let signature = signature(function, kind)?;
    let (input, output) = (&signature.input, &signature.output);
    let doc = format!(
        "Host function contract `{}`, generated by `#[{}]`.",
        name.value(),
        kind.attribute()
    );
    let docs = doc_text(&function.attrs);
    let docs_const = (!docs.is_empty()).then(|| quote!(const DOCS: &'static str = #docs;));
    let implementation = match kind {
        Kind::Static => static_impl(&marker, &signature),
        Kind::WithCtx | Kind::Async => register_impl(&marker, vis, &signature, kind),
    };

    Ok(quote! {
        #function

        #[doc = #doc]
        #vis struct #marker;

        impl ::manivelle::HostContract for #marker {
            const NAME: &'static str = #name;
            #docs_const

            fn kind() -> ::manivelle::HostContractKind {
                ::manivelle::HostContractKind::Function
            }
        }

        impl ::manivelle::HostFunctionSignature for #marker {
            type Input = #input;
            type Output = #output;
        }

        #implementation
    })
}

/// The `///` comments of the function as Markdown: one line per comment line, without the
/// space every `///` leaves in front of its text.
pub(crate) fn doc_text(attrs: &[syn::Attribute]) -> String {
    let lines: Vec<String> = attrs
        .iter()
        .filter(|attr| attr.path().is_ident("doc"))
        .filter_map(|attr| match &attr.meta {
            syn::Meta::NameValue(pair) => match &pair.value {
                syn::Expr::Lit(syn::ExprLit {
                    lit: syn::Lit::Str(text),
                    ..
                }) => Some(text.value()),
                _ => None,
            },
            _ => None,
        })
        .flat_map(|text| {
            text.split('\n')
                .map(|line| line.strip_prefix(' ').unwrap_or(line).to_owned())
                .collect::<Vec<_>>()
        })
        .collect();
    lines.join("\n").trim().to_owned()
}

fn static_impl(marker: &Ident, signature: &Signature) -> TokenStream {
    let call = &signature.call;
    quote! {
        impl ::manivelle::HostFunction for #marker {
            fn call(
                input: <Self as ::manivelle::HostFunctionSignature>::Input,
            ) -> ::core::result::Result<
                <Self as ::manivelle::HostFunctionSignature>::Output,
                ::manivelle::EngineError,
            > {
                #call
            }
        }
    }
}

/// `Marker::register(&registry)`, which registers the function with its handler.
fn register_impl(
    marker: &Ident,
    vis: &syn::Visibility,
    signature: &Signature,
    kind: Kind,
) -> TokenStream {
    let call = &signature.call;
    let params = &signature.params;
    let method = match (kind, signature.with_ctx) {
        (Kind::Async, true) => quote!(async_function_with_caller),
        (Kind::Async, false) => quote!(async_function_with),
        _ => quote!(function_with_caller),
    };
    quote! {
        impl #marker {
            /// Registers this host function, with its handler, in `registry`.
            #vis fn register(
                registry: &::manivelle::InMemoryHostContractRegistry,
            ) -> ::core::result::Result<
                &::manivelle::InMemoryHostContractRegistry,
                ::manivelle::EngineError,
            > {
                registry.#method::<Self>(#params #call)
            }
        }
    }
}

/// Reads the input and output types, and the call of the function.
fn signature(function: &ItemFn, kind: Kind) -> syn::Result<Signature> {
    let types: Vec<&Type> = function
        .sig
        .inputs
        .iter()
        .filter_map(|arg| match arg {
            FnArg::Typed(arg) => Some(arg.ty.as_ref()),
            FnArg::Receiver(_) => None,
        })
        .collect();
    let fn_ident = &function.sig.ident;
    let (returned, fallible) = output_type(function)?;
    let unit: Type = syn::parse_quote!(());
    // The call of the function, wrapped in `Ok` unless it returns a `Result` itself.
    let call = |args: TokenStream| {
        if fallible {
            quote!(#fn_ident(#args))
        } else {
            quote!(::core::result::Result::Ok(#fn_ident(#args)))
        }
    };

    match kind {
        Kind::Static => Ok(Signature {
            input: types.first().map_or(unit, |ty| (*ty).clone()),
            output: returned,
            call: call(if types.is_empty() {
                TokenStream::new()
            } else {
                quote!(input)
            }),
            with_ctx: false,
            params: TokenStream::new(),
        }),
        Kind::WithCtx => Ok(Signature {
            input: types.get(1).map_or(unit, |ty| (*ty).clone()),
            output: returned,
            call: call(if types.len() == 1 {
                quote!(ctx)
            } else {
                quote!(ctx, input)
            }),
            with_ctx: true,
            params: if types.len() == 1 {
                quote!(|ctx, _input|)
            } else {
                quote!(|ctx, input|)
            },
        }),
        Kind::Async => {
            // `check_shape` has already rejected any other arity.
            let (with_ctx, input, resolver) = match types.as_slice() {
                [_, input, resolver] => (true, *input, *resolver),
                [input, resolver] => (false, *input, *resolver),
                _ => {
                    return Err(Error::new(
                        function.sig.inputs.span(),
                        format!("`#[{}]` takes {}", kind.attribute(), kind.arity().1),
                    ));
                }
            };
            Ok(Signature {
                input: input.clone(),
                output: resolver_output(resolver)?,
                call: call(if with_ctx {
                    quote!(ctx, input, resolver)
                } else {
                    quote!(input, resolver)
                }),
                with_ctx,
                params: if with_ctx {
                    quote!(|ctx, input, resolver|)
                } else {
                    quote!(|input, resolver|)
                },
            })
        }
    }
}

/// The `T` of the `HostResolver<T>` an async host function receives.
fn resolver_output(ty: &Type) -> syn::Result<Type> {
    let expected = "the last parameter must be a `HostResolver<Output>`";
    let Type::Path(path) = ty else {
        return Err(Error::new(ty.span(), expected));
    };
    let last = path
        .path
        .segments
        .last()
        .filter(|s| s.ident == "HostResolver");
    let Some(PathArguments::AngleBracketed(generics)) = last.map(|s| &s.arguments) else {
        return Err(Error::new(ty.span(), expected));
    };
    match generics.args.first() {
        Some(GenericArgument::Type(output)) => Ok(output.clone()),
        _ => Err(Error::new(ty.span(), expected)),
    }
}

/// Arguments of the host function attributes: `name = "..."` and the `no_namespace` flag.
#[derive(Default)]
pub(crate) struct HostFnArgs {
    /// The contract name; the full name outside a `#[host_mod]`.
    pub(crate) name: Option<LitStr>,
    /// Opts out of the enclosing `#[host_mod]` prefix; `name` is then the full name.
    pub(crate) no_namespace: bool,
    /// The `reply` type of a `#[host_event]` that is a request.
    pub(crate) reply: Option<Type>,
}

impl HostFnArgs {
    pub(crate) fn parse(args: TokenStream) -> syn::Result<Self> {
        let mut parsed = Self::default();
        parse_args(
            args,
            "expected `name = \"contract.name\"`, and optionally `no_namespace` \
             or, for an event, `reply = Type`",
            |meta| {
                Ok(take_value(meta, "name", &mut parsed.name)?
                    || take_flag(meta, "no_namespace", &mut parsed.no_namespace)
                    || take_value(meta, "reply", &mut parsed.reply)?)
            },
        )?;
        Ok(parsed)
    }
}

fn check_shape(function: &ItemFn, kind: Kind) -> syn::Result<()> {
    let sig = &function.sig;
    if sig.asyncness.is_some() {
        return Err(Error::new(
            sig.asyncness.span(),
            "a host function cannot be `async fn`; use `#[host_fn_async]` with a `HostResolver`",
        ));
    }
    if !sig.generics.params.is_empty() {
        return Err(Error::new(
            sig.generics.span(),
            "a host function cannot be generic",
        ));
    }
    if let Some(FnArg::Receiver(receiver)) = sig.inputs.first() {
        return Err(Error::new(
            receiver.span(),
            "a host function cannot take `self`",
        ));
    }
    let (allowed, expected) = kind.arity();
    if allowed.contains(&sig.inputs.len()) {
        Ok(())
    } else {
        Err(Error::new(
            sig.inputs.span(),
            format!("`#[{}]` takes {expected}", kind.attribute()),
        ))
    }
}

/// The `Output` type, and whether the function returns `Result<Output, EngineError>`;
/// any other return type, or none, is an infallible `Output` the call wraps in `Ok`.
fn output_type(function: &ItemFn) -> syn::Result<(Type, bool)> {
    let ReturnType::Type(_, ty) = &function.sig.output else {
        return Ok((syn::parse_quote!(()), false));
    };
    let Type::Path(path) = ty.as_ref() else {
        return Ok((ty.as_ref().clone(), false));
    };
    let Some(last) = path.path.segments.last().filter(|s| s.ident == "Result") else {
        return Ok((ty.as_ref().clone(), false));
    };
    let PathArguments::AngleBracketed(generics) = &last.arguments else {
        return Err(Error::new(
            ty.span(),
            "expected `Result<Output, EngineError>`",
        ));
    };
    match generics.args.first() {
        Some(GenericArgument::Type(output)) => Ok((output.clone(), true)),
        _ => Err(Error::new(
            ty.span(),
            "expected `Result<Output, EngineError>`",
        )),
    }
}

/// `find_user` → `FindUser`.
fn marker_ident(function: &Ident) -> Ident {
    let name: String = function
        .to_string()
        .trim_start_matches("r#")
        .split('_')
        .filter(|part| !part.is_empty())
        .map(|part| {
            let mut chars = part.chars();
            chars
                .next()
                .map(|first| first.to_uppercase().chain(chars).collect::<String>())
                .unwrap_or_default()
        })
        .collect();
    format_ident!("{}", name, span = function.span())
}
