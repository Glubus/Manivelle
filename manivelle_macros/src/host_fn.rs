//! Expansion of `#[host_fn(name = "...")]`.

use proc_macro2::TokenStream;
use quote::{format_ident, quote};
use syn::{
    Error, FnArg, GenericArgument, Ident, ItemFn, LitStr, PathArguments, ReturnType, Type,
    parse::Parser, spanned::Spanned,
};

/// Expands the attribute: keeps the function and adds the marker type implementing
/// `HostContract`, `HostFunctionSignature` and `HostFunction` for it.
pub(crate) fn expand_host_fn(args: TokenStream, function: &ItemFn) -> syn::Result<TokenStream> {
    let name = HostFnArgs::parse(args.clone())?
        .name
        .ok_or_else(|| Error::new(args.span(), "missing `name = \"contract.name\"`"))?;
    check_shape(function)?;

    let marker = marker_ident(&function.sig.ident);
    let vis = &function.vis;
    let fn_ident = &function.sig.ident;
    let output = ok_type(function)?;
    let (input, call_args) = match function.sig.inputs.first() {
        Some(FnArg::Typed(arg)) => (arg.ty.as_ref().clone(), quote!(input)),
        _ => (syn::parse_quote!(()), quote!()),
    };
    let doc = format!("Host function contract `{}`, generated by `#[host_fn]`.", name.value());

    Ok(quote! {
        #function

        #[doc = #doc]
        #vis struct #marker;

        impl ::manivelle::HostContract for #marker {
            const NAME: &'static str = #name;

            fn kind() -> ::manivelle::HostContractKind {
                ::manivelle::HostContractKind::Function
            }
        }

        impl ::manivelle::HostFunctionSignature for #marker {
            type Input = #input;
            type Output = #output;
        }

        impl ::manivelle::HostFunction for #marker {
            fn call(
                input: <Self as ::manivelle::HostFunctionSignature>::Input,
            ) -> ::core::result::Result<
                <Self as ::manivelle::HostFunctionSignature>::Output,
                ::manivelle::EngineError,
            > {
                #fn_ident(#call_args)
            }
        }
    })
}

/// Arguments of `#[host_fn(...)]`: `name = "..."` and the `no_namespace` flag.
#[derive(Default)]
pub(crate) struct HostFnArgs {
    /// The contract name; the full name outside a `#[host_mod]`.
    pub(crate) name: Option<LitStr>,
    /// Opts out of the enclosing `#[host_mod]` prefix; `name` is then the full name.
    pub(crate) no_namespace: bool,
}

impl HostFnArgs {
    pub(crate) fn parse(args: TokenStream) -> syn::Result<Self> {
        let mut parsed = Self::default();
        let parser = syn::meta::parser(|meta| {
            if meta.path.is_ident("name") && parsed.name.is_none() {
                parsed.name = Some(meta.value()?.parse::<LitStr>()?);
            } else if meta.path.is_ident("no_namespace") && !parsed.no_namespace {
                parsed.no_namespace = true;
            } else {
                return Err(meta.error(
                    "expected `name = \"contract.name\"` and optionally `no_namespace`",
                ));
            }
            Ok(())
        });
        parser.parse2(args)?;
        Ok(parsed)
    }
}

fn check_shape(function: &ItemFn) -> syn::Result<()> {
    let sig = &function.sig;
    if sig.asyncness.is_some() {
        return Err(Error::new(sig.asyncness.span(), "a host function cannot be `async`"));
    }
    if !sig.generics.params.is_empty() {
        return Err(Error::new(sig.generics.span(), "a host function cannot be generic"));
    }
    if sig.inputs.len() > 1 {
        return Err(Error::new(
            sig.inputs.span(),
            "a host function takes at most one input; group fields in a struct",
        ));
    }
    if let Some(FnArg::Receiver(receiver)) = sig.inputs.first() {
        return Err(Error::new(receiver.span(), "a host function cannot take `self`"));
    }
    Ok(())
}

/// The `T` of the declared `Result<T, EngineError>`.
fn ok_type(function: &ItemFn) -> syn::Result<Type> {
    let expected = "expected a return type of `Result<Output, EngineError>`";
    let ReturnType::Type(_, ty) = &function.sig.output else {
        return Err(Error::new(function.sig.span(), expected));
    };
    let Type::Path(path) = ty.as_ref() else {
        return Err(Error::new(ty.span(), expected));
    };
    let last = path.path.segments.last().filter(|s| s.ident == "Result");
    let Some(PathArguments::AngleBracketed(generics)) = last.map(|s| &s.arguments) else {
        return Err(Error::new(ty.span(), expected));
    };
    match generics.args.first() {
        Some(GenericArgument::Type(output)) => Ok(output.clone()),
        _ => Err(Error::new(ty.span(), expected)),
    }
}

/// `find_user` → `FindUser`.
fn marker_ident(function: &Ident) -> Ident {
    let name: String = function
        .to_string()
        .trim_start_matches("r#")
        .split('_')
        .filter(|part| !part.is_empty())
        .map(|part| {
            let mut chars = part.chars();
            chars
                .next()
                .map(|first| first.to_uppercase().chain(chars).collect::<String>())
                .unwrap_or_default()
        })
        .collect();
    format_ident!("{}", name, span = function.span())
}
